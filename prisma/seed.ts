// Misspelled name -> corrected name. The corrected note becomes a main note,
// and the misspelling becomes its alias.
const MISSPELLINGS: Record<string, string> = {
  "Lemon Verbana": "Lemon Verbena",
  "Musk Mallo": "Musk Mallow",
};

const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
});

async function main() {
  const { count } = await prisma.note.createMany({
    data: NOTES.map((name) => ({ name })),
    skipDuplicates: true,
  });
  console.log(
    `Added ${count} of ${NOTES.length} notes (the rest already existed).`,
  );

  await prisma.$transaction(async (tx) => {
    for (const [misspelled, corrected] of Object.entries(MISSPELLINGS)) {
      const main = await tx.note.findUniqueOrThrow({
        where: { name: corrected },
      });
      const alias = await tx.note.findUniqueOrThrow({
        where: { name: misspelled },
      });

      // A main note points to itself.
      await tx.note.update({
        where: { id: main.id },
        data: { mainAliasId: main.id },
      });
      // Anything pointing at the misspelling (including itself, if it was main)
      // now points at the corrected note, so no alias is left on a non-main note.
      await tx.note.updateMany({
        where: { mainAliasId: alias.id },
        data: { mainAliasId: main.id },
      });
      await tx.note.update({
        where: { id: alias.id },
        data: { mainAliasId: main.id },
      });
      console.log(`"${misspelled}" is now an alias of "${corrected}".`);
    }
  });
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
